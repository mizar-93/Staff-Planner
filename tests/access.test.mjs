import assert from 'node:assert/strict';
import {allowed,validKey,workerSchedule,isDeputy,canDelegate,validDeputySchedule} from '../server/access.mjs';
const manager={role:'production_manager',active:true};
const leader={role:'shift_leader',shift_id:'shift-1',active:true};
const worker={role:'worker',shift_id:'shift-1',group_id:'A',active:true};
assert.equal(allowed(leader,'shift-1','staff_people_enc',true),true);
assert.equal(allowed(leader,'shift-2','staff_people_enc'),false);
assert.equal(allowed(leader,'shift-3','staff_production_records_enc',true),false);
assert.equal(allowed(worker,'shift-1','staff_people_enc'),false);
assert.equal(allowed(worker,'shift-1','staff_schedule_enc:2026-10-12',true),false);
assert.equal(allowed(manager,'shift-3','staff_people_enc',true),true);
assert.equal(allowed(manager,'shift-1','staff_todos_enc'),true);
assert.equal(allowed(manager,'shift-1','staff_todos_enc',true),false);
assert.equal(allowed({...leader,active:false},'shift-1','staff_people_enc'),false);
assert.equal(validKey('staff_schedule_enc:2026-10-12'),true);
assert.equal(validKey('app_session_password'),false);
assert.deepEqual(workerSchedule({GD1:{Monday:'a',Tuesday:'b'}},[{id:'a',name:'Ali',groupId:'A',assessment:'private'},{id:'b',name:'Bob',groupId:'B'}],worker),{people:[{id:'a',name:'Ali'}],schedule:{GD1:{Monday:'a',Tuesday:''}}});
console.log('PASS server permissions, shift isolation, manager todo restrictions, worker data projection');
assert.equal(canDelegate(leader,worker),true);
assert.equal(canDelegate(leader,{...worker,shift_id:'shift-2'}),false);
assert.equal(canDelegate(worker,worker),false);
assert.equal(canDelegate(manager,worker),false);
assert.equal(canDelegate(leader,{...worker,active:false}),false);
assert.equal(canDelegate(leader,leader),false);
const deputy={...worker,deputy:true};
assert.equal(isDeputy(deputy),true);
assert.equal(isDeputy({...deputy,deputy:false}),false);
assert.equal(isDeputy({...deputy,active:false}),false);
assert.equal(allowed(deputy,'shift-1','staff_assessments_enc'),false);
assert.equal(allowed(deputy,'shift-1','staff_people_enc',true),false);
assert.equal(allowed(deputy,'shift-2','staff_schedule_enc:2026-10-12',true),false);
assert.equal(validDeputySchedule({GD1:{'Måndag':'a'}},[{id:'a'}]),true);
assert.equal(validDeputySchedule({GD1:{'Måndag':'other-shift-person'}},[{id:'a'}]),false);
assert.equal(validDeputySchedule({GD1:{'invalid-day':'a'}},[{id:'a'}]),false);
assert.equal(validDeputySchedule([],[]),false);
console.log('PASS deputy delegation boundaries, revocation, narrow access, schedule validation');
